#!/usr/bin/env python3
"""Render docs/BENCHMARK_LONGMEMEVAL.md from benchmarks/longmemeval/results.json.

Every figure is read from the result file, for the same reason the validation
document is generated rather than written: a verdict typed by hand is a verdict
no run produced.

Usage:
    python3 scripts/generate_benchmark_doc.py
"""

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_RESULTS = ROOT / "benchmarks" / "longmemeval" / "results.json"
DEFAULT_OUT = ROOT / "docs" / "BENCHMARK_LONGMEMEVAL.md"

BELIEF_STATE_MEANING = {
    "superseded": "current value active, old value deactivated — belief revision happened",
    "both_active": "both values active — accumulated instead of replaced",
    "old_value_never_stored": (
        "current value active, old value absent entirely — the extractor never "
        "produced it, so nothing was there to supersede"
    ),
    "current_value_missing": "the current value never reached the store",
    "no_superseded_statement_annotated": "the instance annotates no earlier value",
}


def _pct(rate: Any) -> str:
    if rate is None:
        return "—"
    return f"{rate:.0%}"


def build(data: Dict[str, Any]) -> str:
    lines: List[str] = []
    add = lines.append

    bench = data["benchmark"]
    engine = data["engine"]
    summary = data["summary"]
    ku = summary["knowledge_update"]
    abstention = summary["abstention"]
    rows: List[Dict[str, Any]] = data["instances"]
    ku_rows = [r for r in rows if not r["abstention"]]
    abs_rows = [r for r in rows if r["abstention"]]
    utterances = sum(r["utterances_total"] for r in rows)

    add("# LongMemEval — first external run")
    add("")
    add(
        "Generated by `scripts/generate_benchmark_doc.py` from "
        "`benchmarks/longmemeval/results.json`. Every number comes from that file."
    )
    add("")
    add(
        f"{bench['name']} ({bench['paper']}), {bench['instances_available']} "
        f"instances available, {summary['instances']} run: {len(ku_rows)} "
        f"knowledge-update and {len(abs_rows)} abstention. "
        f"{utterances} user utterances were ingested in "
        f"{data['wall_clock_seconds']:.0f}s of wall clock against "
        f"`{engine['base_url']}`, an engine with its own store at "
        f"`{engine['memory_db']}`, retrieving `top_k={engine['top_k']}`."
    )
    add("")
    add(
        "**These are not the published LongMemEval scores and cannot be compared "
        "to them.** The paper scores a generated answer with an LLM judge. This "
        "engine generates nothing, so the metrics here are judge-free proxies "
        f"at a {data['metrics']['coverage_threshold']} token-coverage bar, "
        "defined in `benchmarks/README.md`."
    )
    add("")

    add("## Knowledge update")
    add("")
    add("| Metric | Value |")
    add("| --- | --- |")
    add(f"| Instances | {ku['instances']} |")
    add(f"| Answer in the top {engine['top_k']} | {_pct(ku['answer_supported_rate'])} |")
    add(f"| Answer present in the store at all | {_pct(ku['answer_in_store_rate'])} |")
    add(f"| Superseded value returned (a stale read) | {_pct(ku['stale_returned_rate'])} |")
    add(f"| Instances with any deactivated row | {_pct(ku['any_deactivated_row_rate'])} |")
    add(f"| Mean active facts per user | {ku['mean_active_facts']} |")
    add("")
    add("What the store did with each update:")
    add("")
    add("| Belief state | Instances | Meaning |")
    add("| --- | --- | --- |")
    for state, count in sorted(
        ku["belief_state_counts"].items(), key=lambda kv: -kv[1]
    ):
        add(f"| `{state}` | {count} | {BELIEF_STATE_MEANING.get(state, '')} |")
    add("")

    superseded = ku["belief_state_counts"].get("superseded", 0)
    both_active = ku["belief_state_counts"].get("both_active", 0)
    add(
        f"So on this data the supersession path fired {superseded} times and "
        f"accumulated both values {both_active} times. Neither number evidences "
        "belief revision: the binding constraint is upstream, in extraction. "
        f"The current value reached the store in "
        f"{_pct(ku['answer_in_store_rate'])} of instances, and the v0.3.0 "
        "simulation reported the same class of gap (66-69 of 111 utterances "
        "yielding no fact). The engine's natural key is "
        "`user_id:subject:predicate`, so two statements only collide when the "
        "extractor chooses the same predicate for both; on free text it does not."
    )
    add("")

    add("## Abstention")
    add("")
    add("| Metric | Value |")
    add("| --- | --- |")
    add(f"| Instances | {abstention['instances']} |")
    add(
        f"| Returned at least one memory | "
        f"{_pct(abstention['returned_something_rate'])} |"
    )
    add(f"| Mean memories returned | {abstention['mean_returned_count']} |")
    add("")
    add(
        "These questions are unanswerable from the history. `/retrieve` ranks and "
        "returns `top_k` with no confidence floor, so this result is the design "
        "and not a regression. It is measured so the gap has a size: the engine "
        "has no way to say \"I don't know\"."
    )
    add("")

    supported = [r for r in ku_rows if r["answer_supported"]]
    if supported:
        add("## The instances that worked")
        add("")
        for row in supported:
            variant = row.get("answer_variant_matched") or row["gold_answer"]
            add(
                f"- `{row['question_id']}` — matched on `{variant}` via "
                f"`{row['answer_supporting_text']}`, "
                f"{row['store']['active']} active facts for that user"
            )
        add("")
        short = [
            r
            for r in supported
            if len(str(r.get("answer_variant_matched") or "").split()) <= 1
        ]
        if short:
            add(
                "Read the short ones carefully: a gold answer of one content "
                "token is satisfied by that token alone, so "
                + ", ".join(f"`{r['question_id']}`" for r in short)
                + " is weaker evidence than the coverage figure suggests. This "
                "is the proxy's limit, stated rather than smoothed over."
            )
            add("")

    add("## Reproducing this")
    add("")
    add("```bash")
    add("# fetch the dataset and start the benchmark engine: see benchmarks/README.md")
    add(
        "python3 benchmarks/longmemeval/run_benchmark.py "
        f"--engine {engine['base_url']} \\"
    )
    add(f"    --memory-db {engine['memory_db']} --limit {len(ku_rows)}")
    add("python3 scripts/generate_benchmark_doc.py")
    add("```")
    add("")
    add(
        "The extractor is non-deterministic across identical inputs, which is a "
        "known open issue, so a repeat run will not reproduce these figures "
        "exactly. In an earlier pass over instance "
        f"`{ku_rows[0]['question_id']}` the same utterances produced nine active "
        "facts including the answer-bearing one; in this run they produced "
        f"{ku_rows[0]['store']['active']}, without it."
    )
    add("")

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", default=str(DEFAULT_RESULTS))
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()

    results = Path(args.results)
    if not results.exists():
        print(f"missing {results}; run benchmarks/longmemeval/run_benchmark.py first")
        return 1

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(json.loads(results.read_text())))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
